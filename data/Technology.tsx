export const getTechnologyLogo = (logoKey: string): React.ReactElement => {
	const key = logoKey.toLowerCase();
	if (key.includes("next")) return <NextJsLogo />;
	if (key.includes("react")) return <ReactJsLogo />;
	if (key.includes("type") || key.includes("ts")) return <TypeScriptLogo />;
	if (key.includes("node")) return <NodeJsLogo />;
	if (key.includes("mongo")) return <MongoDbLogo />;
	if (key.includes("postgres") || key.includes("sql")) return <PostgreSqlLogo />;
	if (key.includes("tailwind")) return <TailwindCssLogo />;
	if (key.includes("nest")) return <NestJsLogo />;
	if (key.includes("python")) return <PythonLogo />;
	if (key.includes("docker")) return <DockerLogo />;
	return <IconHexagon className="h-8 w-8 text-neutral-800" size={32} />;
};
